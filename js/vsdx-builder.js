  /**
   * Visio-safe SVG: no foreignObject, standard <text> with explicit coords.
   */
  function buildSvg({ nodes, edges, options, pageWidthIn, pageHeightIn }) {
    const px = 96;
    const heightIn = pageHeightIn ?? Math.max(1, ...nodes.map((n) => n.visioY + n.heightIn / 2 + 0.5));
    const widthIn = pageWidthIn ?? Math.max(1, ...nodes.map((n) => n.visioX + n.widthIn / 2 + 0.5));
    const fontPx = (options?.fontSizePt ?? 8) * px / 72;
    const box = (n) => ({ cx: n.visioX * px, cy: (heightIn - n.visioY) * px, w: n.widthIn * px, h: n.heightIn * px });
    const lines = [
      '<?xml version="1.0" encoding="UTF-8"?>',
      `<svg xmlns="http://www.w3.org/2000/svg" width="${widthIn * px}" height="${heightIn * px}" viewBox="0 0 ${widthIn * px} ${heightIn * px}">`,
      '<rect width="100%" height="100%" fill="#fff"/>',
      '<defs><marker id="arrow" markerWidth="7" markerHeight="7" refX="6" refY="3" orient="auto"><path d="M0 0L6 3L0 6Z" fill="#111"/></marker></defs>',
    ];
    function textBlock(text, cx, cy, w, background = false) {
      const capacity = Math.max(1, (w - 10) / fontPx);
      const wrapped = [];
      for (const paragraph of String(text).split("\n")) {
        let line = "", used = 0;
        for (const ch of paragraph) {
          const weight = /[^\x00-\x7f]/.test(ch) ? 1 : 0.55;
          if (line && used + weight > capacity) { wrapped.push(line); line = ""; used = 0; }
          line += ch; used += weight;
        }
        wrapped.push(line);
      }
      if (background) lines.push(`<rect x="${cx - w / 2}" y="${cy - fontPx * wrapped.length * 0.6}" width="${w}" height="${fontPx * wrapped.length * 1.2}" fill="#fff"/>`);
      lines.push(`<text text-anchor="middle" font-family="Arial, PingFang SC, Microsoft YaHei, sans-serif" font-size="${fontPx}" fill="#111">`);
      wrapped.forEach((line, i) => lines.push(`<tspan x="${cx}" y="${cy + (i - (wrapped.length - 1) / 2) * fontPx * 1.2 + fontPx * 0.35}">${esc(line)}</tspan>`));
      lines.push("</text>");
    }
    const byId = new Map(nodes.map((n) => [n.id, n]));
    for (const e of edges) {
      const source = byId.get(e.source), target = byId.get(e.target);
      if (!source || !target) continue;
      const s = box(source), t = box(target);
      const dx = t.cx - s.cx, dy = t.cy - s.cy;
      const horizontal = Math.abs(dx) >= Math.abs(dy);
      const x1 = horizontal ? s.cx + Math.sign(dx) * s.w / 2 : s.cx;
      const x2 = horizontal ? t.cx - Math.sign(dx) * t.w / 2 : t.cx;
      const y1 = horizontal ? s.cy : s.cy + Math.sign(dy) * s.h / 2;
      const y2 = horizontal ? t.cy : t.cy - Math.sign(dy) * t.h / 2;
      lines.push(`<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="#111" stroke-width="0.667" marker-end="url(#arrow)"/>`);
      if (e.text) textBlock(e.text, (x1 + x2) / 2, (y1 + y2) / 2, Math.max(24, e.text.length * fontPx + 8), true);
    }
    for (const n of nodes) {
      const { cx, cy, w, h } = box(n);
      if (n.type === "decision") lines.push(`<polygon points="${cx},${cy - h / 2} ${cx + w / 2},${cy} ${cx},${cy + h / 2} ${cx - w / 2},${cy}" fill="#fff" stroke="#111" stroke-width="0.667"/>`);
      else if (n.type !== "label") lines.push(`<rect x="${cx - w / 2}" y="${cy - h / 2}" width="${w}" height="${h}" rx="${["startEnd", "terminator"].includes(n.type) ? h / 2 : 0}" fill="#fff" stroke="#111" stroke-width="0.667"/>`);
      if (n.text) textBlock(n.text, cx, cy, w * (n.type === "decision" ? 0.833 : 1));
    }
    lines.push("</svg>");
    return lines.join("\n");
  }

